// 커트라인·점수 합격 판정 상담 방침. 공개된 커트라인이 없으니 숫자를 만들지 않고, 현재 위치를 가늠할 방법을 안내한다.
const CUTOFF_PATTERNS = [
  /커트\s*라인|컷트\s*라인|커트|합격\s*(?:선|점|컷|권|점수)|추합\s*권|안정\s*권/,
  /컷\s*(?:이|은|좀|몇|얼마|정보|알려|어느|어떻)/,
  /몇\s*점(?:이면|이어야|정도|은|을|이나)?.{0,12}(?:합격|붙|가능|안정|갈\s*수|갈수)/,
  /\d+(?:\.\d+)?\s*점(?:이면|으로|인데|정도면|나오면|맞으면).{0,16}(?:합격|붙|가능|갈\s*수|갈수|될까|되나|돼|어때|어떄)/,
  /(?:영수합|수물합|영어\s*\d+|수학\s*\d+).{0,6}\d+\s*점/,
];

export function isCutoffQuestion(question: string): boolean {
  return CUTOFF_PATTERNS.some((pattern) => pattern.test(question));
}

export function buildCutoffGuide(): string {
  return [
    "아래는 합격판 운영자의 커트라인·합격 점수 상담 방침이다. 문장을 그대로 외워 반복하지 말고 질문에 맞게 자연스럽게 풀어 쓴다.",
    "- 숫자를 줄 수 없는 이유 세 가지는 빠뜨리지 말고 짧게 말한다: ① 편입은 공식 커트라인을 공개하는 학교가 거의 없다. ② 학교마다 매년 시험 난이도가 다르다. ③ 같은 학교라도 학과마다 합격 점수가 다르다.",
    "- 그래서 커트라인 숫자, 합격권·안정권, 합격 확률을 만들어 말하지 않는다. 인터넷·학원에서 도는 커트라인은 복원 정답과 제보 점수로 만든 추정치라 그대로 믿기 어렵다고 말할 수 있다.",
    "- 자기 위치를 알고 싶어 하면 김영편입 모의고사처럼 응시 인원이 많은 모의고사를 쳐 보는 걸 권한다. 같은 시험을 본 다른 수험생들 사이에서 내 위치를 가늠해 볼 수 있다. 다만 모의고사 점수도 참고 지표이지 합격 기준은 아니라고 덧붙인다.",
    "- 사용자가 점수를 말했으면 그 점수를 짚어 주되 좋다·낮다로 평가하지 않는다. 대신 목표 학교의 시험 과목과 반영 비율을 확인하고 약한 과목을 보완하는 쪽으로 이야기를 잇는다. 시험 과목·반영 비율은 합격판에 학교 이름과 함께 물어보면 모집요강 기준으로 알려줄 수 있다고 안내해도 된다.",
    "- '자료가 없어', '근거를 찾지 못했어'로 답을 끝내지 않는다. 왜 숫자를 줄 수 없는지와 대신 할 수 있는 것을 함께 말한다.",
  ].join("\n");
}
