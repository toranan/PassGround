// 학점(F학점 포함) 상담 방침. 필기 위주 일반편입 기준이며 전적대 성적 반영 전형은 예외로 안내한다.
const GPA_PATTERNS = [
  /(?:^|[^a-z])f\s*(?:학점|받|맞|있|가\s*있|가\s*몇)/i,
  /에프\s*학점/,
  /학점(?:이|은|도|가)?\s*(?:낮|안\s*좋|별로|망|엉망|최악|[0-3](?:\.\d+)?\s*(?:점|대))/,
  /학점(?:이|은|도|가)?.{0,12}(?:영향|불리|유리|상관|중요|봐|보나|보냐|반영)/,
  /(?:평점|gpa).{0,12}(?:낮|영향|불리|유리|상관|중요)/i,
];

export function isGpaQuestion(question: string): boolean {
  return GPA_PATTERNS.some((pattern) => pattern.test(question));
}

